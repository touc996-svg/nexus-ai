"""Persistent API keys with expiry, revocation and rotation.

Keys are generated by the server, shown once, and stored only as a SHA-256 digest. A generated key carries 256
bits of entropy, so a fast hash is appropriate here (a human-chosen password would need a password-hashing
function). The lookup is by digest, so a timing difference reveals nothing about the key itself.

  * Every key expires (``ttl_days`` 1 to 366, default 90): there are no permanent database keys.
  * Revocation takes effect on the next request: nothing is cached.
  * Rotation issues a replacement and shortens the old key's life to an overlap window, so clients can switch
    without downtime. It never lengthens the old key's life.
  * Roles are ``user`` (confined to one user id) and ``admin`` (the operator role). ``user`` is the default;
    an admin key has to be asked for explicitly.

The store supplements the environment keys (``NEXUS_API_KEY`` / ``NEXUS_API_KEYS``); it does not replace them,
and those stay as the bootstrap and break-glass credentials. It is honoured only when
``NEXUS_KEYSTORE_ENABLED`` is true. A store failure never authenticates a request (the middleware answers 503).

Management is by command line, ``python -m app.security.keystore``, run by someone who already has access to
the database. There is deliberately no HTTP endpoint that mints credentials.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import secrets
import sys
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta

from sqlalchemy import Column, DateTime, String
from sqlalchemy.engine import make_url

from app.core.database import DATABASE_URL, Base, SessionLocal, init_db
from app.security.identity import (
    OPERATOR,
    ROLE_ADMIN,
    ROLE_USER,
    SYSTEM_USER,
    Principal,
)

KEY_PREFIX = "nxk_"
MAX_KEY_LENGTH = 256
DEFAULT_TTL_DAYS = 90
MAX_TTL_DAYS = 366
DEFAULT_OVERLAP_DAYS = 7
MAX_OVERLAP_DAYS = 30
MAX_LABEL_LENGTH = 120
ROLES = (ROLE_USER, ROLE_ADMIN)


class ApiKey(Base):
    __tablename__ = "api_keys"

    id = Column(String(24), primary_key=True)
    key_hash = Column(String(64), nullable=False, unique=True, index=True)
    user_id = Column(String(128), nullable=False)
    role = Column(String(16), nullable=False)
    label = Column(String(MAX_LABEL_LENGTH), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False)
    expires_at = Column(DateTime(timezone=True), nullable=False)
    revoked_at = Column(DateTime(timezone=True), nullable=True)


class KeyStoreError(ValueError):
    """An invalid request to the store: a bad argument, or an unknown or inactive key id."""


@dataclass(frozen=True)
class IssuedKey:
    key: str  # the raw key: returned once, never stored
    key_id: str
    user_id: str
    role: str
    expires_at: datetime

    def __repr__(self) -> str:  # never let the raw key reach a log line through repr()
        return f"IssuedKey(key_id={self.key_id!r}, user_id={self.user_id!r}, role={self.role!r}, key=<hidden>)"


def _utcnow() -> datetime:
    return datetime.now(UTC)


def _as_utc(value: datetime) -> datetime:
    """SQLite hands back naive datetimes; everything stored here is UTC."""
    return value if value.tzinfo is not None else value.replace(tzinfo=UTC)


def hash_key(raw_key: str) -> str:
    return hashlib.sha256(raw_key.encode("utf-8")).hexdigest()


def _validate_user_id(user_id: str) -> str:
    # The same rules as NEXUS_API_KEYS entries (hardening.parse_user_keys).
    if not isinstance(user_id, str) or not 1 <= len(user_id) <= 128 or any(ord(c) < 33 for c in user_id):
        raise KeyStoreError("user id must be 1 to 128 printable characters without spaces")
    if user_id == SYSTEM_USER:
        raise KeyStoreError("the user id 'system' is reserved (the shared pool)")
    return user_id


def _validate_days(name: str, value: int, low: int, high: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not low <= value <= high:
        raise KeyStoreError(f"{name} must be a whole number from {low} to {high}")
    return value


class KeyStore:
    def __init__(self, session_factory=None, *, clock=None, initialize: bool = True):
        self.session_factory = session_factory or SessionLocal
        self.clock = clock or _utcnow
        if initialize:
            init_db()

    @contextmanager
    def _session(self):
        db = self.session_factory()
        try:
            yield db
        except Exception:
            db.rollback()
            raise
        finally:
            db.close()

    def _new_row(self, user_id: str, role: str, ttl_days: int, label: str | None, now: datetime):
        raw_key = KEY_PREFIX + secrets.token_urlsafe(32)
        row = ApiKey(
            id="k_" + secrets.token_hex(6),
            key_hash=hash_key(raw_key),
            user_id=user_id,
            role=role,
            label=label,
            created_at=now,
            expires_at=now + timedelta(days=ttl_days),
            revoked_at=None,
        )
        return row, raw_key

    def issue(self, user_id: str, *, role: str = ROLE_USER, ttl_days: int = DEFAULT_TTL_DAYS,
              label: str | None = None) -> IssuedKey:
        user_id = _validate_user_id(user_id)
        if role not in ROLES:
            raise KeyStoreError(f"role must be one of {', '.join(ROLES)}")
        _validate_days("ttl_days", ttl_days, 1, MAX_TTL_DAYS)
        if label is not None and (not isinstance(label, str) or len(label) > MAX_LABEL_LENGTH):
            raise KeyStoreError(f"label must be at most {MAX_LABEL_LENGTH} characters")
        row, raw_key = self._new_row(user_id, role, ttl_days, label, self.clock())
        issued = IssuedKey(raw_key, row.id, user_id, role, row.expires_at)
        with self._session() as db:
            db.add(row)
            db.commit()
        return issued

    def authenticate(self, raw_key: str) -> Principal | None:
        """Return the principal for an active key, or None. Raises only when the store itself fails."""
        if not isinstance(raw_key, str) or not raw_key.startswith(KEY_PREFIX) or len(raw_key) > MAX_KEY_LENGTH:
            return None
        digest = hash_key(raw_key)
        with self._session() as db:
            row = db.query(ApiKey).filter(ApiKey.key_hash == digest).one_or_none()
            if row is None or row.revoked_at is not None or _as_utc(row.expires_at) <= self.clock():
                return None
            role, user_id = row.role, row.user_id
        if role == ROLE_ADMIN:
            return OPERATOR
        if role == ROLE_USER:
            return Principal(user_id=user_id, is_admin=False)
        return None  # an unrecognised role in the table grants nothing

    def revoke(self, key_id: str) -> bool:
        """Revoke a key now. Returns False if it was already revoked."""
        with self._session() as db:
            row = db.get(ApiKey, key_id)
            if row is None:
                raise KeyStoreError("unknown key id")
            if row.revoked_at is not None:
                return False
            row.revoked_at = self.clock()
            db.commit()
            return True

    def rotate(self, key_id: str, *, overlap_days: int = DEFAULT_OVERLAP_DAYS,
               ttl_days: int = DEFAULT_TTL_DAYS) -> IssuedKey:
        """Issue a replacement for an active key; the old key keeps working for ``overlap_days`` at most."""
        _validate_days("overlap_days", overlap_days, 0, MAX_OVERLAP_DAYS)
        _validate_days("ttl_days", ttl_days, 1, MAX_TTL_DAYS)
        now = self.clock()
        with self._session() as db:
            old = db.get(ApiKey, key_id)
            if old is None:
                raise KeyStoreError("unknown key id")
            if old.revoked_at is not None or _as_utc(old.expires_at) <= now:
                raise KeyStoreError("only an active key can be rotated")
            new_row, raw_key = self._new_row(old.user_id, old.role, ttl_days, old.label, now)
            issued = IssuedKey(raw_key, new_row.id, new_row.user_id, new_row.role, new_row.expires_at)
            old.expires_at = min(_as_utc(old.expires_at), now + timedelta(days=overlap_days))
            db.add(new_row)
            db.commit()
            return issued

    def list_keys(self, *, include_inactive: bool = False) -> list[dict]:
        """Key metadata only: never the key and never its digest."""
        now = self.clock()
        with self._session() as db:
            rows = db.query(ApiKey).order_by(ApiKey.created_at, ApiKey.id).all()
            result = []
            for row in rows:
                if row.revoked_at is not None:
                    status = "revoked"
                elif _as_utc(row.expires_at) <= now:
                    status = "expired"
                else:
                    status = "active"
                if status != "active" and not include_inactive:
                    continue
                result.append({
                    "key_id": row.id, "user_id": row.user_id, "role": row.role, "label": row.label,
                    "status": status, "created_at": _as_utc(row.created_at).isoformat(),
                    "expires_at": _as_utc(row.expires_at).isoformat(),
                    "revoked_at": _as_utc(row.revoked_at).isoformat() if row.revoked_at else None,
                })
            return result


# ---- command line -------------------------------------------------------------------------------

def describe_database(url) -> str:
    """The database URL with any password hidden, for the command line to show which database it is changing."""
    return make_url(url).render_as_string(hide_password=True)


def _print_issued(issued: IssuedKey, out, err) -> None:
    print(f"key_id:     {issued.key_id}", file=out)
    print(f"user:       {issued.user_id}", file=out)
    print(f"role:       {issued.role}", file=out)
    print(f"expires_at: {_as_utc(issued.expires_at).isoformat()}", file=out)
    print(f"key:        {issued.key}", file=out)
    print("Store this key now: it is not saved and cannot be shown again.", file=err)
    if os.getenv("NEXUS_KEYSTORE_ENABLED", "").strip().lower() not in {"1", "true", "yes", "on"}:
        print("note: stored keys are honoured only when NEXUS_KEYSTORE_ENABLED=true on the server.", file=err)


def main(argv=None, *, store: KeyStore | None = None, out=None, err=None) -> int:
    out = out or sys.stdout
    err = err or sys.stderr
    parser = argparse.ArgumentParser(prog="python -m app.security.keystore", description="Manage NEXUS API keys.")
    commands = parser.add_subparsers(dest="command", required=True)

    issue = commands.add_parser("issue", help="issue a new key (shown once)")
    issue.add_argument("--user", required=True, help="user id the key is bound to")
    issue.add_argument("--role", choices=ROLES, default=ROLE_USER, help="default: user; admin must be asked for")
    issue.add_argument("--ttl-days", type=int, default=DEFAULT_TTL_DAYS)
    issue.add_argument("--label", default=None)

    listing = commands.add_parser("list", help="list keys (metadata only)")
    listing.add_argument("--all", action="store_true", help="include expired and revoked keys")

    revoke = commands.add_parser("revoke", help="revoke a key immediately")
    revoke.add_argument("key_id")

    rotate = commands.add_parser("rotate", help="issue a replacement; the old key expires after the overlap")
    rotate.add_argument("key_id")
    rotate.add_argument("--overlap-days", type=int, default=DEFAULT_OVERLAP_DAYS)
    rotate.add_argument("--ttl-days", type=int, default=DEFAULT_TTL_DAYS)

    args = parser.parse_args(argv)
    if store is None:
        try:
            store = KeyStore()
        except Exception as exc:  # noqa: BLE001 - report the kind of failure only; a DB error can carry credentials
            print(f"error: could not open the key store ({type(exc).__name__})", file=err)
            return 1
        # DATABASE_URL defaults to a file relative to the working directory: say which database this is, so running
        # the command from the wrong directory (and so changing a different database) is visible.
        print(f"database: {describe_database(DATABASE_URL)}", file=err)
    try:
        if args.command == "issue":
            _print_issued(store.issue(args.user, role=args.role, ttl_days=args.ttl_days, label=args.label), out, err)
        elif args.command == "rotate":
            _print_issued(store.rotate(args.key_id, overlap_days=args.overlap_days, ttl_days=args.ttl_days), out, err)
        elif args.command == "revoke":
            changed = store.revoke(args.key_id)
            print("revoked" if changed else "already revoked", file=out)
        else:
            for item in store.list_keys(include_inactive=args.all):
                print(f"{item['key_id']}  {item['status']:<8} {item['role']:<5} {item['user_id']:<20} "
                      f"expires {item['expires_at']}  {item['label'] or ''}".rstrip(), file=out)
    except KeyStoreError as exc:
        print(f"error: {exc}", file=err)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
